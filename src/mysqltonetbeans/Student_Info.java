    private void tbl_dataMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_dataMouseClicked
        int r = tbl_data.getSelectedRow();
        String click = (tbl_data.getModel().getValueAt(r, 0).toString());
        String sql = "SELECT * FROM student_info WHERE IDNumber='"+click+"'";
        try{
            ps = conn.prepareStatement(sql);
            rs=ps.executeQuery();
            if(rs.next()){
                int id = rs.getInt(1);
                String lastname = rs.getString(2);
                String firstname = rs.getString(3);
                String middlename = rs.getString(4);
                String department= rs.getString(5);
                txt_id.setText(Integer.toString(id));
                txt_lastname.setText(lastname);
                txt_firstname.setText(firstname);
                txt_middlename.setText(middlename);
                txt_department.setText(department);
            }
            
        }catch(Exception e){
             JOptionPane.showMessageDialog(null, e);
        }
        
    }//GEN-LAST:event_tbl_dataMouseClicked

