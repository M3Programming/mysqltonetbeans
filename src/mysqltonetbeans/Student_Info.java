    private void btn_findidActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findidActionPerformed
        String id = txt_id.getText();
        String sql = "SELECT * FROM student_info WHERE IDNumber = '"+id+"'";
        try{
            ps = conn.prepareStatement(sql);
            rs=ps.executeQuery();
            if(rs.next()){
               String lastname = rs.getString(2);
               String firstname= rs.getString(3);
               String middlename = rs.getString(4);
               String department = rs.getString(5);
               txt_lastname.setText(lastname);
               txt_firstname.setText(firstname);
               txt_middlename.setText(middlename);
               txt_department.setText(department);
               
            }else{
                JOptionPane.showMessageDialog(null, "No record found");
                txt_lastname.setText("");
               txt_firstname.setText("");
               txt_middlename.setText("");
               txt_department.setText("");
            }
            
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btn_findidActionPerformed

